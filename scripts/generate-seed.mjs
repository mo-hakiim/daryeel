// Generates two SQL files from the bundled catalogue (src/data/*.ts and the i18n
// category names):
//
//   supabase/seed.sql          first-time fill of an empty database. Rows whose slug
//                              already exists are skipped, so it never overwrites edits.
//   supabase/sync-catalog.sql  brings an existing database up to date with the bundled
//                              catalogue after a site update (new products, moved or
//                              renamed categories, new photos and text). It keeps the
//                              price and in-stock values set in the admin dashboard.
//
//   node scripts/generate-seed.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { CATEGORY_COVER, CATEGORY_IDS, SUBCATEGORY_IDS } from "../src/data/catalog.ts";
import { products } from "../src/data/products.ts";
import { en } from "../src/i18n/en.ts";
import { so } from "../src/i18n/so.ts";

const q = (v) => (v === undefined || v === null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => (v === undefined || v === null ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const arr = (list) =>
  list && list.length ? `array[${list.map(q).join(", ")}]::text[]` : "'{}'::text[]";
// Product photos are uploaded to the bucket as "<key>.webp" (scripts/upload-images.mjs).
const imagePath = (key) => `${key}.webp`;

/** Categories renamed in a site update: old slug -> new slug (kept so the row id, and every product link, survives). */
const RENAMED_CATEGORIES = { minerals: "supplements" };

const CATEGORY_COLS =
  "slug, name, name_so, tagline, tagline_so, description, description_so, cover_image, sort_order";
const categoryRows = CATEGORY_IDS.map((id, i) => {
  const e = en.categories[id];
  const s = so.categories[id];
  return `  (${[q(id), q(e.name), q(s.name), q(e.tagline), q(s.tagline), q(e.description), q(s.description), q(imagePath(CATEGORY_COVER[id])), i].join(", ")})`;
}).join(",\n");

const PRODUCT_COLS =
  "slug, name, name_so, brand, aliases, category_id, subcategory, facts, description, description_so, benefits, supplied_benefits, caution, image_labels, price, images, in_stock, is_featured, sort_order";
const productRows = products
  .map((p, i) => {
    const values = [
      q(p.slug),
      q(p.name),
      q(p.nameSo),
      q(p.brand),
      arr(p.aliases),
      `(select id from public.categories where slug = ${q(p.category)})`,
      q(p.subcategory),
      q(p.facts),
      q(p.description.en),
      q(p.description.so),
      json(p.benefits),
      json(p.suppliedBenefits),
      json(p.caution),
      json(p.imageLabels),
      "null", // no prices in the bundled data; set them in the dashboard
      arr(p.images.map(imagePath)),
      "true",
      p.featured ? "true" : "false",
      i,
    ];
    return `  (${values.join(", ")})`;
  })
  .join(",\n");

const subcategoryCheck = [
  "alter table public.products drop constraint if exists products_subcategory_check;",
  `alter table public.products add constraint products_subcategory_check check (subcategory in (${SUBCATEGORY_IDS.map(q).join(", ")}));`,
];

/* ---------------- seed.sql ---------------- */
const seed = [
  "-- =====================================================================",
  "-- DARYEEL WELLNESS — seed data (generated by scripts/generate-seed.mjs)",
  "-- Run AFTER schema.sql: Supabase → SQL Editor → New query → paste → Run.",
  "-- Existing rows (same slug) are left untouched, so running it twice is safe.",
  "-- =====================================================================",
  "",
  "begin;",
  "",
  ...subcategoryCheck,
  "",
  `insert into public.categories (${CATEGORY_COLS}) values`,
  categoryRows + "\non conflict (slug) do nothing;",
  "",
  `insert into public.products (${PRODUCT_COLS}) values`,
  productRows + "\non conflict (slug) do nothing;",
  "",
  "commit;",
  "",
];

/* ---------------- sync-catalog.sql ---------------- */
const sync = [
  "-- =====================================================================",
  "-- DARYEEL WELLNESS — catalogue sync (generated by scripts/generate-seed.mjs)",
  "-- Brings the database in line with the website's bundled catalogue after an",
  "-- update: renamed categories, moved products, new products, photos and text.",
  "--",
  "-- Supabase → SQL Editor → New query → paste this whole file → Run.",
  "-- Safe to run more than once.",
  "--",
  "-- KEPT from the dashboard: price, in-stock.",
  "-- OVERWRITTEN with the website's version: names, descriptions, benefits,",
  "-- photos, category, featured flag and order of every product listed here.",
  "-- Products added only in the dashboard are not touched.",
  "-- =====================================================================",
  "",
  "begin;",
  "",
  ...subcategoryCheck,
  "",
  "-- Renamed categories keep their row (and every product link).",
  ...Object.entries(RENAMED_CATEGORIES).map(
    ([from, to]) =>
      `update public.categories set slug = ${q(to)} where slug = ${q(from)} and not exists (select 1 from public.categories where slug = ${q(to)});`,
  ),
  "",
  `insert into public.categories (${CATEGORY_COLS}) values`,
  categoryRows,
  "on conflict (slug) do update set",
  "  name = excluded.name, name_so = excluded.name_so, tagline = excluded.tagline, tagline_so = excluded.tagline_so,",
  "  description = excluded.description, description_so = excluded.description_so,",
  "  cover_image = excluded.cover_image, sort_order = excluded.sort_order;",
  "",
  `insert into public.products (${PRODUCT_COLS}) values`,
  productRows,
  "on conflict (slug) do update set",
  "  name = excluded.name, name_so = excluded.name_so, brand = excluded.brand, aliases = excluded.aliases,",
  "  category_id = excluded.category_id, subcategory = excluded.subcategory, facts = excluded.facts,",
  "  description = excluded.description, description_so = excluded.description_so,",
  "  benefits = excluded.benefits, supplied_benefits = excluded.supplied_benefits, caution = excluded.caution,",
  "  image_labels = excluded.image_labels, images = excluded.images,",
  "  is_featured = excluded.is_featured, sort_order = excluded.sort_order;",
  "",
  "commit;",
  "",
  "-- Check: products per category",
  "select c.name, count(p.id) as products from public.categories c left join public.products p on p.category_id = c.id group by c.name, c.sort_order order by c.sort_order;",
  "",
];

const write = (file, lines) =>
  writeFileSync(fileURLToPath(new URL(`../supabase/${file}`, import.meta.url)), lines.join("\n"));
write("seed.sql", seed);
write("sync-catalog.sql", sync);
console.log(
  `Wrote ${CATEGORY_IDS.length} categories and ${products.length} products to supabase/seed.sql and supabase/sync-catalog.sql`,
);
