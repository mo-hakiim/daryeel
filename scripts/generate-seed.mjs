// Generates supabase/seed.sql from the bundled catalogue (src/data/*.ts and the i18n
// category names), so the database starts with exactly the products the site shows today.
//
//   node scripts/generate-seed.mjs
//
// Re-running the seed in Supabase never overwrites edits: rows whose slug already
// exists are skipped.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { CATEGORY_COVER, CATEGORY_IDS } from "../src/data/catalog.ts";
import { products } from "../src/data/products.ts";
import { en } from "../src/i18n/en.ts";
import { so } from "../src/i18n/so.ts";

const q = (v) => (v === undefined || v === null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const json = (v) => (v === undefined || v === null ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const arr = (list) =>
  list && list.length ? `array[${list.map(q).join(", ")}]::text[]` : "'{}'::text[]";
// Product photos are uploaded to the bucket as "<key>.webp" (scripts/upload-images.mjs).
const imagePath = (key) => `${key}.webp`;

const lines = [
  "-- =====================================================================",
  "-- DARYEEL WELLNESS — seed data (generated by scripts/generate-seed.mjs)",
  "-- Run AFTER schema.sql: Supabase → SQL Editor → New query → paste → Run.",
  "-- Existing rows (same slug) are left untouched, so running it twice is safe.",
  "-- =====================================================================",
  "",
  "begin;",
  "",
  "insert into public.categories (slug, name, name_so, tagline, tagline_so, description, description_so, cover_image, sort_order) values",
  CATEGORY_IDS.map((id, i) => {
    const e = en.categories[id];
    const s = so.categories[id];
    return `  (${[q(id), q(e.name), q(s.name), q(e.tagline), q(s.tagline), q(e.description), q(s.description), q(imagePath(CATEGORY_COVER[id])), i].join(", ")})`;
  }).join(",\n") + "\non conflict (slug) do nothing;",
  "",
];

lines.push(
  "insert into public.products (slug, name, name_so, brand, aliases, category_id, subcategory, facts, description, description_so, benefits, supplied_benefits, caution, image_labels, price, images, in_stock, is_featured, sort_order) values",
);
lines.push(
  products
    .map((p, i) => {
      const values = [
        q(p.slug),
        q(p.name),
        q(p.nameSo),
        q(p.brand),
        arr(p.aliases),
        `(select id from public.categories where slug = ${q(p.category)})`,
        q(p.subcategory),
        q(p.facts),
        q(p.description.en),
        q(p.description.so),
        json(p.benefits),
        json(p.suppliedBenefits),
        json(p.caution),
        json(p.imageLabels),
        "null", // no prices on the site yet
        arr(p.images.map(imagePath)),
        "true",
        p.featured ? "true" : "false",
        i,
      ];
      return `  (${values.join(", ")})`;
    })
    .join(",\n") + "\non conflict (slug) do nothing;",
);
lines.push("", "commit;", "");

const out = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));
writeFileSync(out, lines.join("\n"));
console.log(
  `Wrote ${CATEGORY_IDS.length} categories and ${products.length} products to supabase/seed.sql`,
);
