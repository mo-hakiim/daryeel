// Runs before every build (`npm run build` / `bun run build`):
//
//  1. Catalogue snapshot — reads categories and products from Supabase (anon key,
//     read-only) into src/data/catalog-snapshot.json, so the static pages, product
//     structured data and sitemap match what the owner manages in the dashboard.
//     If Supabase isn't configured or can't be reached, the snapshot is removed and
//     the build uses the bundled catalogue (src/data/products.ts) instead.
//  2. public/sitemap.xml — every public page plus every category and product.
//  3. public/robots.txt — allows everything except /admin and points to the sitemap.
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { CATEGORY_IDS } from "../src/data/catalog.ts";
import { products as bundledProducts } from "../src/data/products.ts";

const SITE = "https://daryeelwellness.fit";
const root = fileURLToPath(new URL("..", import.meta.url));
const SNAPSHOT = `${root}src/data/catalog-snapshot.json`;
if (existsSync(`${root}.env`)) process.loadEnvFile(`${root}.env`);

const url = (process.env.VITE_SUPABASE_URL ?? "").trim().replace(/\/+$/, "");
const key = (process.env.VITE_SUPABASE_ANON_KEY ?? "").trim();

async function rows(table, query) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), 10_000);
  try {
    const res = await fetch(`${url}/rest/v1/${table}?${query}`, {
      headers: { apikey: key },
      signal: ctrl.signal,
    });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return await res.json();
  } finally {
    clearTimeout(timer);
  }
}

/* ---------- 1. Snapshot ---------- */
let snapshot = null;
if (/^https:\/\/[^/]+$/.test(url) && key) {
  try {
    const [categories, products] = await Promise.all([
      rows("categories", "select=*&order=sort_order.asc,name.asc"),
      rows("products", "select=*&order=sort_order.asc,created_at.asc"),
    ]);
    if (categories.length && products.length)
      snapshot = { fetchedAt: new Date().toISOString(), categories, products };
    else console.warn("catalogue: Supabase returned no rows — using the bundled catalogue");
  } catch (e) {
    console.warn(`catalogue: Supabase unreachable (${e.message}) — using the bundled catalogue`);
  }
} else {
  console.warn("catalogue: no Supabase settings — using the bundled catalogue");
}
if (snapshot) writeFileSync(SNAPSHOT, JSON.stringify(snapshot));
else if (existsSync(SNAPSHOT)) rmSync(SNAPSHOT);

/* ---------- 2. Sitemap ---------- */
const slugById = new Map((snapshot?.categories ?? []).map((c) => [c.id, c.slug]));
const categories = snapshot
  ? snapshot.categories.map((c) => ({ slug: c.slug }))
  : CATEGORY_IDS.map((slug) => ({ slug }));
const products = snapshot
  ? snapshot.products
      .filter((p) => slugById.has(p.category_id))
      .map((p) => ({ slug: p.slug, lastmod: p.updated_at }))
  : bundledProducts.map((p) => ({ slug: p.slug }));

const PAGES = [
  ["/", "1.0", "weekly"],
  ["/products/", "0.9", "weekly"],
  ["/consultation/", "0.8", "monthly"],
  ["/services/", "0.7", "monthly"],
  ["/about/", "0.6", "monthly"],
  ["/contact/", "0.7", "yearly"],
];
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");
const entry = (loc, priority, changefreq, lastmod) =>
  `  <url><loc>${esc(SITE + loc)}</loc>${lastmod ? `<lastmod>${String(lastmod).slice(0, 10)}</lastmod>` : ""}<changefreq>${changefreq}</changefreq><priority>${priority}</priority></url>`;

const lines = [
  ...PAGES.map(([p, pr, f]) => entry(p, pr, f)),
  ...categories.map((c) => entry(`/products/${c.slug}/`, "0.8", "weekly")),
  ...products.map((p) => entry(`/product/${p.slug}/`, "0.7", "weekly", p.lastmod)),
];
writeFileSync(
  `${root}public/sitemap.xml`,
  `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by scripts/prepare-build.mjs on each build. Do not edit. -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${lines.join("\n")}\n</urlset>\n`,
);

/* ---------- 3. robots.txt ---------- */
const robots = `User-agent: *\nAllow: /\nDisallow: /admin\n\nSitemap: ${SITE}/sitemap.xml\n`;
if (
  !existsSync(`${root}public/robots.txt`) ||
  readFileSync(`${root}public/robots.txt`, "utf8") !== robots
) {
  writeFileSync(`${root}public/robots.txt`, robots);
}

console.log(
  `prepare-build: ${snapshot ? "live" : "bundled"} catalogue · sitemap with ${PAGES.length} pages, ${categories.length} categories, ${products.length} products`,
);
